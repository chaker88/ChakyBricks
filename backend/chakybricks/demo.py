def create_sample_dashboard(services: Services) -> Dashboard:
    """Generates the sample table and (re)creates the sample dashboard on it."""
    services.sql.run(_SAMPLE_SQL, f"sample-{uuid.uuid4().hex}")
    spec = DashboardSpec.model_validate(sample_spec())
    for existing in services.dashboards.list():
        if existing.name == SAMPLE_NAME:
            return services.dashboards.update(existing.id, spec=spec)
    return services.dashboards.create(
        SAMPLE_NAME, spec, "Generated sample data and every tile type."
    )
