SAMPLE_TABLE = "demo_sales"
SAMPLE_NAME = "Sales overview (sample)"
SAMPLE_ROWS = 200_000
CATEGORY = "الفئة"

# Dates run backwards from today so "last 90 days" always has data; amounts are deterministic.
_SAMPLE_SQL = f"""
CREATE OR REPLACE TABLE {SAMPLE_TABLE} AS
WITH raw AS (
  SELECT
    i AS order_id,
    CAST(current_date AS DATE) - CAST(hash(i * 7919) % 700 AS INTEGER) AS order_date,
    CAST(hash(i * 31) % 10 AS INTEGER) AS p,
    CAST(hash(i * 17) % 12 AS INTEGER) AS r,
    CAST(hash(i * 13) % 10 AS INTEGER) AS c,
    1 + CAST(hash(i * 5) % 6 AS INTEGER) AS quantity,
    (hash(i * 3) % 21) / 100.0 AS discount
  FROM range({SAMPLE_ROWS}) t(i)
)
SELECT
  order_id,
  order_date,
  ['North America', 'Europe', 'MENA', 'Asia Pacific', 'Latin America', 'Africa']
    [1 + [0, 0, 0, 1, 1, 1, 2, 2, 3, 3, 4, 5][r + 1]] AS region,
  ['Laptop', 'Monitor', 'Keyboard', 'Mouse', 'Desk', 'Chair', 'Lamp', 'Headset', 'Webcam',
   'Dock'][p + 1] AS product,
  ['إلكترونيات', 'إلكترونيات', 'ملحقات', 'ملحقات', 'أثاث', 'أثاث', 'أثاث', 'ملحقات', 'إلكترونيات',
   'ملحقات'][p + 1] AS "{CATEGORY}",
  ['Online', 'Online', 'Online', 'Online', 'Retail', 'Retail', 'Retail', 'Partner', 'Partner',
   'Partner'][c + 1] AS channel,
  quantity,
  CAST([1200, 320, 90, 40, 450, 280, 60, 110, 75, 190][p + 1] AS DOUBLE) AS unit_price,
  CAST(round(discount, 2) AS DOUBLE) AS discount,
  CAST(round(quantity * [1200, 320, 90, 40, 450, 280, 60, 110, 75, 190][p + 1] * (1 - discount)
    * (1 + 0.5 * (700 - (current_date - order_date)) / 700.0), 2) AS DOUBLE) AS revenue,
  CAST(round(quantity * [1200, 320, 90, 40, 450, 280, 60, 110, 75, 190][p + 1]
    * (1 + 0.5 * (700 - (current_date - order_date)) / 700.0) * 0.92, 2) AS DOUBLE)
    AS target_revenue
FROM raw
"""


def _tile(
    kind: str, title: str, x: int, y: int, w: int, h: int, config: dict[str, Any] | None = None
) -> dict[str, Any]:
    tile: dict[str, Any] = {
        "id": uuid.uuid4().hex[:10],
        "type": kind,
        "title": title,
        "layout": {"x": x, "y": y, "w": w, "h": h},
        "config": config or {},
    }
    if kind != "text":
        tile["source"] = {"kind": "table", "table": f"main.{SAMPLE_TABLE}"}
    return tile


def _metric(agg: str, column: str | None = None, label: str = "", **extra: Any) -> dict[str, Any]:
    return {"agg": agg, "column": column, "label": label, **extra}


def _kpi(title: str, x: int, metric: dict[str, Any]) -> dict[str, Any]:
    config = {
        "metrics": [metric],
        "compare": {"mode": "previous_period", "column": "order_date"},
        "trend": {"column": "order_date", "grain": "week"},
    }
    return _tile("kpi", title, x, 3, 6, 5, config)


